#!/usr/bin/env python3
"""Regenerate dependency-free REST bindings from the checked-in canonical contract."""
import json, re, subprocess, sys
from pathlib import Path
root=Path(__file__).resolve().parents[1]
spec=json.loads((root/'rest/openapi.json').read_text())
def name(s):
 return ''.join({'id':'ID','url':'URL','uri':'URI','json':'JSON','html':'HTML','pkce':'PKCE'}.get(x, x[:1].upper()+x[1:]) for x in re.split('[_-]',s))
def typ(s):
 if '$ref' in s:return s['$ref'].split('/')[-1]
 t=s.get('type')
 if t is None and (isinstance(s.get('const'),str) or all(isinstance(v,str) for v in s.get('enum',[None]))):t='string'
 nullable=isinstance(t,list) and 'null' in t
 if isinstance(t,list):t=next((x for x in t if x!='null'),None)
 if t=='array':return '[]'+typ(s.get('items',{}))
 if t=='object':return 'map[string]json.RawMessage'
 v={'string':'string','integer':'int64','number':'float64','boolean':'bool'}.get(t,'json.RawMessage')
 return '*'+v if nullable and v!='json.RawMessage' else v
def write(filename, source):
 formatted=subprocess.run(['gofmt'],input=source,text=True,capture_output=True,check=True).stdout
 target=root/'rest'/filename
 if '--check' in sys.argv:
  if target.read_text()!=formatted:raise SystemExit(f'{filename} needs regeneration')
 else:target.write_text(formatted)
lines=['// Code generated by scripts/generate-rest.py; DO NOT EDIT.','package rest','import "encoding/json"']
for n,s in spec['components']['schemas'].items():
 if 'properties' in s:
  lines.append('type '+n+' struct {')
  for k,v in s['properties'].items():
   # Nullable optional fields use RawMessage for omitted / explicit null / zero.
   optional=k not in s.get('required',[])
   t=typ(v)
   if optional:
    nullable=isinstance(v.get('type'),list) and 'null' in v['type']
    if nullable:t='json.RawMessage'
    elif t!='json.RawMessage' and not t.startswith(('[]','map[','*')):t='*'+t
   lines.append(f'{name(k)} {t} `json:"{k}{",omitempty" if optional else ""}"`')
  lines.append('}')
 else:lines.append('type '+n+' '+typ(s))
write('models.gen.go','\n'.join(lines)+'\n')
ops={}
for path,methods in spec['paths'].items():
 for method,o in methods.items():
  if method not in ['get','post','patch','put','delete'] or o.get('x-fern-server-name')!='rest':continue
  ops[o['operationId']]={'Method':method.upper(),'Path':path,'Summary':o['summary']}
lines=['// Code generated by scripts/generate-rest.py; DO NOT EDIT.','package rest','import "context"','var operations = map[string]Operation{']
for n,o in sorted(ops.items()):lines.append(json.dumps(n)+': {Method: '+json.dumps(o['Method'])+', Path: '+json.dumps(o['Path'])+', Summary: '+json.dumps(o['Summary'])+'},')
lines.append('}')
for n,o in sorted(ops.items()):
 params=re.findall(r'{([^}]+)}',o['Path'])
 args=', '.join(p+' string' for p in params)
 if args:args+=', '
 lines.append('// '+name(n)+' '+o['Summary']+'.')
 lines.append('func (c *Client) '+name(n)+'(ctx context.Context, '+args+'options *Options) (*Response, error) {')
 values=', '.join(json.dumps(p)+': '+p for p in params)
 lines.append('return c.Call(ctx, '+json.dumps(n)+', map[string]string{'+values+'}, options)\n}')
write('operations.gen.go','\n'.join(lines)+'\n')
print(f'Generated {len(ops)} REST operations and {len(spec["components"]["schemas"])} schemas')
